const CODES_BY_LENGTH = Object.keys(AREA_CODES).sort((a, b) => b.length - a.length)

/* 固定電話の10桁だけを取り出す。携帯・IP電話・フリーダイヤルは地域が分からないので対象外。 */
export function landlineDigits(value) {
  if (!value) return null
  const half = String(value).replace(/[０-９]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0))
  const d = half.replace(/\D/g, '')
  if (d.length !== 10 || !d.startsWith('0')) return null
  if (['070', '080', '090', '050'].includes(d.slice(0, 3))) return null
  if (['0120', '0800'].includes(d.slice(0, 4))) return null
  return d
}

/* 電話番号から都道府県を引く。分からないときは null。 */
export function prefectureFromPhone(...values) {
  const found = new Set()
  for (const v of values) {
    const d = landlineDigits(v)
    if (!d) continue
    const code = CODES_BY_LENGTH.find(c => d.startsWith(c))
    if (!code) continue
    const pref = AREA_CODES[code]
    if (!pref) return null          // 県またぎの局番。推測しない
    found.add(pref)
  }
  if (found.size !== 1) return null // 番号ごとに県が違うときも推測しない
  return [...found][0]
}
